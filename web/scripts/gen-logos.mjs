// Writes src/logos.ts: monochrome 24x24 brand marks for the assets DCAC lists, from simple-icons.
// Run after changing the asset list: node scripts/gen-logos.mjs
import { writeFileSync } from "node:fs";
import * as si from "simple-icons";

const map = {
  AAPL: "siApple",
  GOOGL: "siGoogle",
  META: "siMeta",
  MSTR: "siMicrostrategy",
  NVDA: "siNvidia",
  SPCX: "siSpacex",
  TSLA: "siTesla",
  ETH: "siEthereum",
  cbBTC: "siBitcoin",
  cbETH: "siCoinbase",
  LINK: "siChainlink",
};

const out = {};
for (const [symbol, key] of Object.entries(map)) if (si[key]) out[symbol] = si[key].path;
// Microsoft's mark is four squares; drawn here since simple-icons no longer ships it.
out.MSFT = "M2 2h9.5v9.5H2zM12.5 2H22v9.5h-9.5zM2 12.5h9.5V22H2zM12.5 12.5H22V22h-9.5z";

writeFileSync(
  new URL("../src/logos.ts", import.meta.url),
  `// Generated by scripts/gen-logos.mjs from simple-icons (CC0). Brand marks belong to their owners.\nexport const LOGOS: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`wrote ${Object.keys(out).length} logos`);
